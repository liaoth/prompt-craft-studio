import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const SECTION_CONFIG = {
  "12.1": { category: "灯光", targetField: "lighting", expected: 70 },
  "12.2": { category: "风格", targetField: "style", expected: 103 },
  "12.3": { category: "构图", targetField: "composition", expected: 55 },
  "12.4": { category: "环境与背景", targetField: "environment", expected: 79 },
  "12.5": { category: "细节与精度", targetField: "custom", expected: 25 },
  "12.6": { category: "情绪", targetField: "mood", expected: 27 },
  "12.7": { category: "色彩", targetField: "color", expected: 58 },
  "12.8": { category: "视角与镜头", targetField: "camera", expected: 59 },
  "12.9": { category: "细节与精度", targetField: "custom", expected: 40 },
  "12.10": { category: "渲染与3D", targetField: "medium", expected: 36 },
  "12.11": { category: "材质", targetField: "material", expected: 40 },
};

const CORRECTIONS = new Map([
  ["bisexual lighting", { content: "Split lighting", name: "双侧照明" }],
  ["global illuminations", { content: "Global illumination", name: "全局照明" }],
  ["fullbody", { content: "Full body" }],
  ["extreme closeup", { content: "Extreme close-up" }],
  [
    "national geographic",
    { content: "National Geographic photography", name: "国家地理摄影" },
  ],
]);

const input = process.argv[2];
if (!input) {
  throw new Error(
    "Usage: node scripts/extract-section12-phrases.mjs <MidJourney学习.md> [output.ts]",
  );
}

const output = resolve(
  process.argv[3] ?? "lib/prompt/default-phrases-section12.ts",
);
const markdown = readFileSync(resolve(input), "utf8");
const rows = parseSection12(markdown);
const counts = Object.fromEntries(
  Object.keys(SECTION_CONFIG).map((section) => [
    section,
    rows.filter((row) => row.sourceSection === section).length,
  ]),
);

for (const [section, config] of Object.entries(SECTION_CONFIG)) {
  if (counts[section] !== config.expected) {
    throw new Error(
      `${section} expected ${config.expected} rows, received ${counts[section] ?? 0}`,
    );
  }
}
if (rows.length !== 592) {
  throw new Error(`Section 12 expected 592 rows, received ${rows.length}`);
}

const seen = new Set();
const phrases = [];
for (const row of rows) {
  const config = SECTION_CONFIG[row.sourceSection];
  const correction = CORRECTIONS.get(normalizeEnglish(row.content));
  const content = correction?.content ?? normalizeDisplayText(row.content);
  const name = correction?.name ?? normalizeDisplayText(row.name);
  const key = normalizeEnglish(content);
  if (seen.has(key)) continue;
  seen.add(key);
  phrases.push({
    id: `default-${row.sourceSection.replace(".", "-")}-${config.targetField}-${String(row.rowNumber).padStart(3, "0")}`,
    name,
    category: config.category,
    content,
    targetField: config.targetField,
    sortOrder: row.rowNumber - 1,
    sourceSection: row.sourceSection,
  });
}

const source = `// Generated by scripts/extract-section12-phrases.mjs.
// Source rows are validated against MidJourney学习.md section 12.1-12.11.
// Do not edit this file manually.

export const SECTION12_SOURCE_COUNTS = ${JSON.stringify(counts, null, 2)} as const;

export const SECTION12_SOURCE_ROW_COUNT = ${rows.length} as const;

export const SECTION12_PHRASES = ${JSON.stringify(phrases, null, 2)} as const;
`;

writeFileSync(output, source, "utf8");
console.log(
  `Generated ${phrases.length} unique Section 12 phrases from ${rows.length} rows at ${output}`,
);

function parseSection12(source) {
  const result = [];
  let active = false;
  let sourceSection = "";
  const sectionRows = new Map();

  for (const line of source.split(/\r?\n/)) {
    if (line.startsWith("### 12. 图片词库全文转表格")) {
      active = true;
      continue;
    }
    if (active && /^##\s/.test(line) && !line.startsWith("###")) break;
    if (!active) continue;

    const heading = line.match(/^####\s+(12\.\d+)\s+/);
    if (heading) {
      sourceSection = heading[1];
      if (!SECTION_CONFIG[sourceSection]) {
        throw new Error(`Unexpected Section 12 heading: ${sourceSection}`);
      }
      continue;
    }

    const cells = line.match(/^\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|$/);
    if (!cells || !sourceSection) continue;
    const content = cells[1].trim();
    const name = cells[2].trim();
    if (content === "English" || /^-+$/.test(content)) continue;
    const rowNumber = (sectionRows.get(sourceSection) ?? 0) + 1;
    sectionRows.set(sourceSection, rowNumber);
    result.push({ sourceSection, rowNumber, content, name });
  }
  return result;
}

function normalizeEnglish(value) {
  return value.trim().replace(/\s+/g, " ").toLocaleLowerCase("en-US");
}

function normalizeDisplayText(value) {
  return value.trim().replace(/\s+/g, " ");
}
